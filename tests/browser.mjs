import {chromium} from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const stories=JSON.parse(fs.readFileSync('data/stories.json','utf8'));
assert.equal(fs.readFileSync('artifacts/hong-kong-story-atlas.html','utf8'),fs.readFileSync('hong-kong-story-atlas.html','utf8'),'Committed portable HTML must match the source build');
fs.mkdirSync('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:960}});
page.on('pageerror',e=>errors.push(e.message));
await page.route(/^https?:\/\//,r=>r.abort());
const home=pathToFileURL(path.resolve('index.html')).href;
async function count(n){await page.waitForFunction(n=>document.querySelectorAll('#story-list .story-card').length===n,n);}
try{
  await page.goto(home);await count(36);
  assert.equal(await page.locator('#atlas-svg').count(),1,'Offline geographic map must exist');
  assert.ok(await page.locator('#atlas-svg [data-map-ids]').count(),'Offline map needs real story markers');
  await page.locator('#region').selectOption('离岛');await count(stories.filter(s=>s.region==='离岛').length);
  await page.locator('#reset-filters').click();await count(36);
  await page.locator('#theme').selectOption('食物');
  await count(stories.filter(s=>s.themes.includes('食物')).length);
  await page.locator('#reset-filters').click();
  await page.locator('#search').fill('a-place-that-does-not-exist');await count(0);
  await page.locator('#reset-filters').click();await count(36);
  await page.locator('#story-list .story-card[data-open="mei-ho-house"]').click();
  await page.locator('#reader').waitFor({state:'visible'});
  assert.equal((await page.locator('#reader-title').innerText()).trim(),stories.find(s=>s.id==='mei-ho-house').title);
  const source=page.locator('#reader [data-source-ref]').first();
  await source.click();
  assert.ok(await page.locator('#story-sources').evaluate(el=>el.open),'Paragraph citation must open source details');
  await page.locator('#save-story').click();assert.equal(await page.locator('#save-story').getAttribute('aria-pressed'),'true');
  await page.locator('#mark-read').click();assert.equal(await page.locator('#mark-read').getAttribute('aria-pressed'),'true');
  await page.keyboard.press('Escape');assert.ok(await page.locator('#reader').isHidden());
  await page.locator('#saved-only').check();await count(1);
  await page.reload();await page.waitForFunction(()=>document.readyState==='complete');
  await page.locator('#reset-filters').click();await count(36);
  await page.locator('#saved-only').check();await count(1);
  await page.locator('#reset-filters').click();await count(36);
  await page.locator('#basemap-toggle').click();
  await page.waitForFunction(()=>!document.getElementById('basemap-toggle').disabled);
  assert.ok(await page.locator('#diagram-map').isVisible(),'Blocked network map must retain offline geography');
  await page.locator('#view-timeline').click();
  assert.equal(await page.locator('#timeline-content .timeline-item').count(),36);
  await page.screenshot({path:'artifacts/timeline-desktop.png',fullPage:true});
  await page.locator('#view-memory').click();
  assert.equal(await page.locator('#memory-content .memory-card').count(),36);
  await page.locator('#memory-content summary').first().click();
  assert.ok(await page.locator('#memory-content details').first().evaluate(el=>el.open));
  await page.locator('#view-map').click();
  await page.locator('#routes-toggle').click();
  const route=page.locator('[data-route]').first();await route.click();
  assert.ok(await page.locator('#story-list .story-card').count()>1,'A route must contain multiple actual stories');
  await page.locator('#reset-filters').click();
  await page.goto(home+'#story=lin-heung');
  await page.locator('#reader').waitFor({state:'visible'});
  assert.ok((await page.locator('#reader-title').innerText()).includes('蒸笼'));
  assert.ok((await page.locator('#reader').innerText()).includes('2026'),'Deep-linked article must include new location history');
  await page.locator('#reader-close').click();
  await page.screenshot({path:'artifacts/atlas-desktop.png',fullPage:true});
  const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  phone.on('pageerror',e=>errors.push(e.message));
  await phone.route(/^https?:\/\//,r=>r.abort());
  await phone.goto(home+'#story=kowloon-walled-city');
  await phone.locator('#reader').waitFor({state:'visible'});
  assert.ok(await phone.locator('#reader-close').isVisible());
  assert.equal(await phone.locator('#reader').getAttribute('aria-modal'),'true');
  assert.ok(await phone.locator('#atlas').evaluate(el=>el.inert),'Phone reader must isolate the covered map from focus');
  for(let i=0;i<12;i++){await phone.keyboard.press('Tab');assert.ok(await phone.evaluate(()=>document.getElementById('reader').contains(document.activeElement)),'Phone reader must retain keyboard focus');}
  assert.ok((await phone.locator('#reader-title').innerText()).includes('南门'));
  assert.ok(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Phone page must fit viewport');
  await phone.screenshot({path:'artifacts/reader-phone.png',fullPage:true});
  await phone.locator('#reader-close').click();
  const marker=await phone.locator('#atlas-svg [data-map-ids]').first().boundingBox();
  assert.ok(marker&&marker.width>=28&&marker.height>=28,'Phone map markers must retain readable pixel size');
  await phone.locator('#search').fill('奶茶');
  await phone.waitForFunction(()=>document.querySelectorAll('#story-list .story-card').length>0);
  await phone.screenshot({path:'artifacts/atlas-phone.png',fullPage:true});
  const portable=await browser.newPage();
  await portable.route(/^https?:\/\//,r=>r.abort());
  portable.on('pageerror',e=>errors.push(e.message));
  await portable.goto(pathToFileURL(path.resolve('artifacts/hong-kong-story-atlas.html')).href);
  await portable.waitForFunction(()=>document.querySelectorAll('#story-list .story-card').length===36);
  assert.equal(await portable.locator('#atlas-svg').count(),1,'Portable file needs offline map');
  const noStorage=await browser.newPage();
  await noStorage.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage unavailable');}}));
  await noStorage.route(/^https?:\/\//,r=>r.abort());
  await noStorage.goto(home);
  await noStorage.waitForFunction(()=>document.querySelectorAll('#story-list .story-card').length===36);
  assert.deepEqual(errors,[],'No uncaught browser errors');
  fs.writeFileSync('artifacts/browser-results.json',JSON.stringify({status:'passed',stories:36,checks:['offline geography','region/theme/search filters','empty results','reader','paragraph citations','saved/read persistence','timeline','memory','reading routes','deep links','phone layout','portable HTML','storage denial'],uncaughtErrors:errors},null,2));
  console.log('Browser verification passed: desktop, phone, offline, portable HTML and storage denial.');
  for(const name of ['atlas-desktop','reader-phone'])console.log('ATLAS_PREVIEW_'+name+':'+fs.readFileSync('artifacts/'+name+'.png').toString('base64'));
}finally{await browser.close();}
